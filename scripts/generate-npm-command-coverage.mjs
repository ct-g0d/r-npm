// Classify commands from the behavioral gate. Never promote help-only evidence.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const reportPath = path.resolve(process.argv[2] || path.join(repo, 'docs/npm-replacement-results-2026-11-13.json'));
const report = JSON.parse(fs.readFileSync(reportPath));
if (!report.expected_cases || report.results.length !== report.expected_cases || report.results.some(r => !r.command)) {
  throw new Error('Incomplete behavioral report; refusing to generate coverage');
}
const rawPath = path.join(repo, 'docs/npm-command-coverage-raw.json');
const catalog = JSON.parse(fs.readFileSync(rawPath));
const coverage = catalog.map(({command, aliases}) => {
  const probes = report.results.filter(r => r.command === command);
  if (!probes.length) throw new Error(`No behavioral probe for ${command}`);
  const successful = probes.some(r => r.npm.exit === 0 && r.rnpm.exit === 0);
  const failures = probes.filter(r => !r.match);
  const missing = probes.some(r => r.npm.exit === 0 && /Unknown command:|ERR_UNSUPPORTED_COMMAND/.test(r.rnpm.stdout + r.rnpm.stderr));
  const status = missing ? 'missing' : failures.length || !successful ? 'partial' : 'matching';
  const diffs = failures.map(r => `${r.name}: ${Object.entries(r.comparison).filter(([,same]) => !same).map(([key]) => key).join(', ')}`);
  if (!successful) diffs.push('No successful operation demonstrated (negative/unsupported/interactive probe only)');
  return {command, aliases, status, diffs: diffs.join('; ') || 'All registered behavioral probes match on this Windows host; broader behavior is unverified.',
    checkMethod: probes.map(r => r.args.join(' ')).join('; '),
    probes: probes.map(r => ({name:r.name,args:r.args,npmExit:r.npm.exit,rnpmExit:r.rnpm.exit,match:r.match,comparison:r.comparison})),
    evidence:path.relative(repo,reportPath).replaceAll('\\','/'), binary_sha256:report.binary_sha256};
});
const counts = Object.fromEntries(['matching','partial','missing'].map(status => [status,coverage.filter(r => r.status === status).length]));
fs.writeFileSync(rawPath,JSON.stringify(coverage,null,2)+'\n');
const escape = text => text.replaceAll('|','\\|').replaceAll('\n',' ');
const lines = [
  '# npm command behavioral coverage', '',
  `Oracle: npm ${report.npm}, Node ${report.node}, ${report.platform}. Candidate SHA-256: \`${report.binary_sha256}\`.`, '',
  `Generated by \`node scripts/generate-npm-command-coverage.mjs\` from [the behavioral report](${path.basename(reportPath)}). The Markdown and [raw JSON](npm-command-coverage-raw.json) use the same results.`, '',
  '| Commands | Matching | Partial | Missing |', '|---:|---:|---:|---:|',
  `| ${coverage.length} | ${counts.matching} | ${counts.partial} | ${counts.missing} |`, '',
  'Matching means every registered behavioral probe for that command matched, including a successful operation. Partial includes differing outputs, filesystem effects or registry mutations, and commands demonstrated only through errors. Missing means npm succeeded while rnpm reported an unsupported command. These are probe classifications, not a percentage of npm implemented.', '',
  'The catalog retains the 73 previously tracked canonical/legacy entries. `set-script` is a negative compatibility probe because npm 11 removed it. The separate npx-style exec probe is in the detailed report. None of these entries is based on `--help` alone; `help` itself is tested as a command.', '',
  'All registry probes use a loopback mock with synthetic credentials. They do not establish real account login, browser/TTY, OTP, private-registry, OIDC, publication, or cross-platform compatibility. `publish` is tested only with `--dry-run`. No performance claim is derived from these probes.', '',
  '| Command | Aliases | Status | Behavioral commands | Evidence / differences |',
  '|---|---|---|---|---|',
  ...coverage.map(r => `| \`${r.command}\` | ${escape(r.aliases || '-')} | ${r.status} | ${escape(r.checkMethod)} | ${escape(r.diffs)} |`), '',
];
fs.writeFileSync(path.join(repo,'docs/npm-command-coverage.md'),lines.join('\n'));
console.log(JSON.stringify({commands:coverage.length,...counts}));
